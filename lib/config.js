// ----- המגירה הנפרדת של "מקושרים לרבי" -----
// המערכת יושבת על אותו פרויקט Firebase של המערכת הקודמת, אבל כל האוספים
// שלה נושאים קידומת ייחודית. כך הנתונים כאן מתחילים ריקים לגמרי ואינם
// נפגשים עם נתונים של מערכת אחרת - גם לא בקריאה.
// כל גישה למסד עוברת דרך col() שלמטה; אין בקוד אף שם אוסף ללא קידומת.
export const COLLECTION_PREFIX = "mekusharim_";

export function col(name) {
  return `${COLLECTION_PREFIX}${name}`;
}

// קידומת מקבילה למפתחות שנשמרים בדפדפן (התחברות, טיוטות, פופאפ),
// כדי שגם האחסון המקומי יהיה נפרד ולא יתנגש עם מערכת אחרת.
export const STORAGE_PREFIX = "mekusharim_";
