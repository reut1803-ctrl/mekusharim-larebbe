// הטלפון של המועמד הוא פרט רגיש: הוא גלוי רק למנהלת, לצופה ולנציג/ה
// שמייצג/ת אותו (כולל מחליף/ה בחופשה) - כדי שיהיה זמין ליצירת קשר בהתאמה.
export const PRIVATE_FIELD_KEYS = ["phone"];

// השדות שמוצגים לכל מי שרואה את הכרטיס, לפי ההרשאה.
export function visibleFields(canSeeSensitive) {
  return canSeeSensitive ? PERSONAL_FIELDS : PERSONAL_FIELDS.filter((f) => !PRIVATE_FIELD_KEYS.includes(f.key));
}

// שם מלא נגזר תמיד משם פרטי + שם משפחה, ונשמר בשדה fullName.
// כל שאר המערכת (התאמות, משימות, יומן פעילות, ייצוא) ממשיכה לעבוד מולו.
export function buildFullName(form) {
  const joined = [form.firstName, form.lastName].filter(Boolean).join(" ").trim();
  return joined || (form.fullName || "").trim();
}

// פיצול שם מלא קיים לשם פרטי ומשפחה - לתאימות עם כרטיסים שנוצרו בעבר.
export function splitFullName(fullName) {
  const parts = (fullName || "").trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return { firstName: "", lastName: "" };
  return { firstName: parts[0], lastName: parts.slice(1).join(" ") };
}

